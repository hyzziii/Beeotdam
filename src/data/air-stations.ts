/**
 * 지역별 대기질 측정소.
 *
 * 자동 생성된 파일이라 손으로 고치지 않는다. 측정소가 바뀌면 생성기를 다시 돌린다.
 *
 * 에어코리아는 지역이 아니라 측정소 단위로 값을 준다. 그래서 지역 좌표에서 가장 가까운
 * 측정소를 미리 골라 둔다. 이름으로 맞추지 않고 좌표 거리로 고른 이유는, 측정소 이름이
 * 행정구역과 다른 경우가 많기 때문이다(한강대로·청계천로·도산대로 등).
 *
 * 도시대기 측정소만 쓴다. 도로변대기는 차량 배기 영향을 크게 받아 그 동네 공기를
 * 대표하지 않는다.
 *
 * 30km보다 먼 측정소는 넣지 않았다. 옹진군(백령도)은 가장 가까운 인천 측정소가
 * 158km 떨어져 있어 그 값을 그 지역 공기라고 할 수 없다. 그런 지역은 목록에 없다.
 *
 * sido는 조회에 넘길 sidoName이다. 에어코리아가 '전남광주'를 통합 이름으로 받아 주므로
 * 우리 시/도 이름을 그대로 쓴다. 주소로 시/도를 알아내면 안 된다 — 주소가 '서울'과
 * '서울특별시', '경기도', '전북특별자치도', '전남광주통합특별시'로 뒤섞여 있다.
 *
 * sido는 에어코리아가 쓰는 이름이다. 우리가 합친 '전남광주'는 저쪽에서 광주·전남으로
 * 나뉘어 있어 지역마다 어느 쪽으로 조회할지 함께 적어 둔다.
 */

